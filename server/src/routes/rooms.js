/**
 * Rooms + pairing routes.
 *
 *   POST /api/rooms             → create (host, i.e. the PC)
 *   POST /api/rooms/:code/join  → join with code (+ optional QR join token)
 *   POST /api/rooms/:code/qr    → fresh join token + QR image (members only)
 */
import { Router } from 'express'
import QRCode from 'qrcode'
import { PORT, PUBLIC_PORT, publicBaseUrl } from '../config.js'
import {
  createJoinToken, createRoom, joinRoom, roomFromHeaders,
} from '../services/rooms.js'
import { lanAddresses } from '../utils/lan.js'
import { allow, retryAfterMs } from '../utils/rateLimit.js'
import { ApiError } from '../utils/errors.js'

const router = Router()

/** 30 create/join attempts per minute per IP. Guessing a 6-digit code stays pointless. */
router.use('/api/rooms', (req, res, next) => {
  const key = `room:${req.ip}`
  if (allow(key, 30, 60_000)) return next()
  res.set('Retry-After', String(Math.ceil(retryAfterMs(key) / 1000) || 30))
  next(new ApiError('RATE_LIMITED', 'Too many attempts — wait a minute and try again.', 429))
})

/**
 * Host → creates its library. Returns code + member secret + first join token
 * + the LAN URL candidates; the QR itself is generated by the /qr endpoint.
 */
router.post('/api/rooms', (req, res) => {
  const { room, ...pairing } = createRoom()
  res.status(201).json({
    code: room.code,
    secret: room.secret,
    ...pairing, // ← includes joinToken (joinUrl built later; expiresAt as ms)
  })
})

/** Phone → joins the room; receives the member secret in return. */
router.post('/api/rooms/:code/join', (req, res) => {
  const room = joinRoom(req.params.code, req.body?.token)
  res.json({ code: room.code, secret: room.secret })
})

/**
 * Rotate the join token and render the QR. `iface` lets the host pick the LAN
 * address that should go inside the URL when our auto-detection guessed wrong.
 *
 * Only members can call this — the QR generator never takes arbitrary URLs, so
 * it cannot be abused to phish other users.
 */
router.post('/api/rooms/:code/qr', async (req, res, next) => {
  try {
    const room = roomFromHeaders(req.headers)
    if (room.code !== req.params.code) {
      throw new ApiError('FORBIDDEN', 'This device is not a member of that library.', 403)
    }
    const pairing = createJoinToken(room.id)
    const ifaces = lanAddresses().map(({ name, address }) => ({ name, address }))
    const pick = req.body?.iface
    const publicBase = publicBaseUrl()
    let base
    if (pick === '__public__') {
      // QR that goes out over a tunnel (phone on another network)
      if (!publicBase) {
        throw new ApiError('NO_TUNNEL', 'No public address is configured — set PUBLIC_HOST on the server first.', 400)
      }
      base = publicBase
    } else if (publicBase && !pick) {
      // tunnel deployments default to the public address until overridden
      base = publicBase
    } else {
      const chosen = pick
        ? ifaces.find((i) => i.address === pick) ?? ifaces[0]
        : ifaces[0]
      base = chosen ? `http://${chosen.address}:${PUBLIC_PORT}` : `http://localhost:${PORT}`
    }
    const joinUrl = `${base}/#/join?code=${room.code}&token=${pairing.joinToken}`
    const qrSvg = await QRCode.toString(joinUrl, {
      type: 'svg',
      margin: 1,
      errorCorrectionLevel: 'M',
      color: { dark: '#16130F', light: '#EDE6D8' },
    })
    res.json({
      ...pairing, // joinToken, joinTokenExpiresAt, lanUrl, lanIfaces, port
      chosenUrl: joinUrl.split('/#/')[0],
      joinUrl,
      qrSvg,
      // surfaces the cross-network URL in the panel when the tunnel env is set
      publicUrl: publicBase ?? null,
    })
  } catch (err) {
    next(err)
  }
})

export default router
